-- ---------------------------------------------------------------------
-- Notes on enabling RLS and setting policies
-- ---------------------------------------------------------------------
-- 1. `alter table ... enable row level security;` turns RLS ON. With no
--    policies defined, this blocks ALL access except from the service
--    role key — safe by default.
-- 2. Policies are additive: a row is visible/writable if ANY matching
--    policy allows it.
-- 3. `auth.uid()` returns the logged-in user's ID inside a Postgres
--    session authenticated via Supabase Auth (anon/authenticated key).
--    It returns NULL for the service role key, which is why service-role
--    writes still work even though no policy explicitly allows them —
--    the service role bypasses RLS entirely.
-- 4. TODO: review and tighten these policies before production — in
--    particular add rate limiting at the application layer, since RLS
--    alone does not prevent an authenticated user from spamming scan
--    inserts (see the in-memory limiter in src/functions/run-scan —
--    replace with a real one before relying on it).
-- 5. The service role key (used by run-scan, generate-report, and the
--    Stripe webhook) bypasses RLS by default in Supabase — no extra GRANT
--    statements are required for it to insert/update. If you ever create
--    a *different*, non-service-role Postgres role for backend code, grant
--    it explicitly, e.g.:
--      grant insert, update on public.scans, public.scan_results to my_backend_role;
