-- ---------------------------------------------------------------------
-- monitored_targets
-- One row per site a subscribed customer wants scanned on a recurring
-- schedule (see .github/workflows/scheduled-scans.yml, which queries
-- this table joined against active subscriptions). Separate from `scans`
-- because `scans` is a log of individual runs, not a standing list of
-- what to scan next.
-- ---------------------------------------------------------------------
create table if not exists public.monitored_targets (
  id uuid primary key default gen_random_uuid(),
  owner uuid not null references auth.users (id) on delete cascade,
  target_url text not null,
  created_at timestamptz not null default now(),
  unique (owner, target_url)
);

alter table public.monitored_targets enable row level security;

create policy "Users can view their own monitored targets"
  on public.monitored_targets for select
  using (owner = auth.uid());

create policy "Users can manage their own monitored targets"
  on public.monitored_targets for insert
  with check (owner = auth.uid());

create policy "Users can delete their own monitored targets"
  on public.monitored_targets for delete
  using (owner = auth.uid());

-- Writes to this table should only happen via the Stripe webhook handler
-- using the service role key — no INSERT/UPDATE policy is defined for
-- regular users on purpose.

-- ---------------------------------------------------------------------
-- verifications
-- Real domain-ownership proof: a DNS TXT record or a file at
-- /.well-known/hebridescyber-verify.txt containing `token`. Populated and
-- checked by src/functions/verify-ownership and src/lib/ownership.ts.
-- Once verified_at is set, run-scan trusts scans against that domain for
-- that owner without needing the (weaker) token-echo fallback.
-- ---------------------------------------------------------------------
create table if not exists public.verifications (
  id uuid primary key default gen_random_uuid(),
  owner uuid not null references auth.users (id) on delete cascade,
  domain text not null,
  token text not null,
  method text check (method in ('dns', 'file')),
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  unique (owner, domain)
);

alter table public.verifications enable row level security;

create policy "Users can view their own verifications"
  on public.verifications for select
  using (owner = auth.uid());

-- Inserts/updates happen via the service role key in verify-ownership
-- only — no end-user write policy is defined on purpose, same reasoning
-- as `subscriptions` above.

-- ---------------------------------------------------------------------
-- blog_posts
-- Weekly cybersecurity newsletter, published to /blog on the marketing
