-- After running, confirm RLS is ON for every table holding user data —
-- Supabase does NOT enable it by default on tables created via SQL.

-- ---------------------------------------------------------------------
-- users (profile data — Supabase Auth already manages auth.users; this
-- table holds app-specific profile fields keyed to the same id)
-- ---------------------------------------------------------------------
create table if not exists public.users (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  full_name text,
  company_name text,
  -- Grants access to /admin (src/app/admin/page.tsx, src/pages/api/admin/overview.ts).
  -- Only ever set this via the SQL editor or the seed script — there is no
  -- UI path that lets a user grant themselves admin.
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.users enable row level security;

create policy "Users can view their own profile"
  on public.users for select
  using (id = auth.uid());

create policy "Users can update their own profile"
  on public.users for update
  using (id = auth.uid())
  -- Users can update their own name/company, but NOT flip is_admin on
  -- themselves — enforced by checking the new row still matches the old
  -- value via a trigger would be more bulletproof, but for this scaffold
  -- the simpler control is: the browser client only ever sends full_name/
  -- company_name in its update calls (see any future profile-edit UI).
  -- TODO: add a BEFORE UPDATE trigger that rejects is_admin changes from
  -- anything but the service role, rather than relying on client discipline.
  with check (id = auth.uid());

-- ---------------------------------------------------------------------
-- scans
-- ---------------------------------------------------------------------
create table if not exists public.scans (
  id uuid primary key default gen_random_uuid(),
  owner uuid not null references auth.users (id) on delete cascade,
  target_url text not null,
  status text not null default 'pending' check (status in ('pending', 'running', 'completed', 'failed')),
  -- Proof-of-ownership token, generated by run-scan when the scan row is
  -- created and required back (via X-Scan-Token header or ?verification=
  -- query param) before the scan actually runs. See src/functions/run-scan
  -- and docs/security.md — this is a lightweight stub, not a real DNS/file
  -- ownership check yet.
  proof_token text,
  owner_verified boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.scans enable row level security;

-- Example RLS policy: users can only view their own scans.
create policy "Users can view their scans"
  on public.scans for select
  using (owner = auth.uid());

create policy "Users can insert their own scans"
  on public.scans for insert
  with check (owner = auth.uid());

-- TODO: add an UPDATE policy scoped to owner if users should be able to
-- cancel/retry their own scans from the dashboard.
-- Note: the run-scan Azure Function uses the SERVICE ROLE key, which
-- bypasses RLS entirely — that's expected and required for it to write
-- results and update status for any scan.

-- ---------------------------------------------------------------------
-- scan_results
-- ---------------------------------------------------------------------
create table if not exists public.scan_results (
  id uuid primary key default gen_random_uuid(),
  scan_id uuid not null references public.scans (id) on delete cascade,
  results jsonb not null,
  -- Plain-English summary and 0-100 score, both produced by
  -- summariseResults()/scoreFromFindings() in src/lib/scanners.ts.
  summary text,
  score integer check (score between 0 and 100),
  created_at timestamptz not null default now()
);

alter table public.scan_results enable row level security;

-- Results are only visible if the user owns the parent scan.
create policy "Users can view results for their own scans"
  on public.scan_results for select
  using (
    exists (
      select 1 from public.scans
      where scans.id = scan_results.scan_id
        and scans.owner = auth.uid()
    )
  );

