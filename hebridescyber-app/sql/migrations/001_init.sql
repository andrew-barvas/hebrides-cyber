create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  -- One row per user: the Stripe webhook handler upserts on this column
  -- (see src/pages/api/stripe/webhook.ts, onConflict: "owner"). If you
  -- need multiple concurrent subscriptions per user later, drop this
  -- unique constraint and key the upsert on stripe_subscription_id instead.
